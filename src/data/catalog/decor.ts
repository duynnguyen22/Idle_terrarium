export type DecorId = (typeof DECOR_LITERAL)[number]['id']

/** Widened to `DecorDef` so optional glow fields can be read on every piece. */
export const DECOR: readonly DecorDef[] = DECOR_LITERAL

export const DECOR_BY_ID = Object.fromEntries(DECOR.map((d) => [d.id, d])) as Readonly<
  Record<DecorId, DecorDef>
>

const THEME_LABELS: readonly (readonly [DecorTheme, string])[] = [
  ['village', 'Village and garden'],
  ['japan', 'Japanese garden'],
  ['people', 'Little people'],
  ['animals', 'Animals'],
  ['lights', 'Mushrooms and lights'],
]

/** Catalog headings for the decor tab, in display order. Every decor id appears in exactly one group. */
export const DECOR_GROUPS: readonly { label: string; ids: readonly DecorId[] }[] = THEME_LABELS.map(
  ([theme, label]) => ({
    label,
    ids: DECOR_LITERAL.filter((d) => d.theme === theme).map((d) => d.id),
  }),
)

export const DECOR_FOOT = 30

/** Converts the sprite's foot line at design y = +30 into normalized tank units for a given scale. */
export function decorFootN(scale: number): number {
  return (DECOR_FOOT * (scale || 1) * 0.36) / 128 / 2
}
